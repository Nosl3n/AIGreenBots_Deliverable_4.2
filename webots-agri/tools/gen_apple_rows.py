#!/usr/bin/env python3
"""Write rows of AppleTree (tall spindle) into a Webots world, between the APPLE_ROWS markers.

Layout: 5 rows at x = -5 ... 5 (the FieldTerrain beds), 2.5 m apart, running south->north (+Y), centred on the
origin — the robot start, the workers' trajectories and the field polygon in openfield_concept assume it.

An orchard is not uniform, so each tree gets its own size, drawn per tree from three classes:
  * mature  (most trees): 2.3-3.2 m tall, canopy radius 0.48-0.65 m, full leaf and fruit load;
  * young   (replants):   1.3-1.8 m, radius 0.30-0.42 m, few leaves, little or no fruit;
  * weak    (stressed):   mature height but sparse leaves and a light crop.
The PROTO's `seed` then varies where the branches, leaves and fruit go inside that envelope.

Spacing against the Husky A300: the canopy is widest at the bottom (the lowest scaffolds), i.e. at robot
height, so the LARGEST canopy radius bounds the corridor: 2.5 m rows minus 2 x 0.65 m leaves 1.2 m clear for
a 0.69 m robot. Trees 1.25 m apart in a row (tall-spindle orchards plant ~1 m apart; a little wider here
so the LiDAR still sees between neighbours).

Usage: gen_apple_rows.py [world.wbt] [--rows 5] [--per-row 12] [--row-spacing 2.5] [--tree-spacing 1.25]
                         [--jitter 0.05] [--young 0.12] [--weak 0.08] [--seed 21] [--z 0.14]
Prints the corridor centre lines and the planted area, for openfield_concept's Field.Polygon.
"""
import argparse
import pathlib
import random
import re

BEGIN = "# ---- APPLE_ROWS BEGIN (generated by webots-agri/tools/gen_apple_rows.py; do not edit by hand) ----"
END = "# ---- APPLE_ROWS END ----"
MAX_CANOPY_RADIUS = 0.65
ROBOT_WIDTH = 0.69


def tree_params(rng, kind):
    """Size and load of one tree. Leaf and fruit counts scale with the canopy volume (~ r^2 h)."""
    if kind == "young":
        h, r = rng.uniform(1.3, 1.8), rng.uniform(0.30, 0.42)
        leaf_density, fruit_load = rng.uniform(0.7, 1.0), rng.uniform(0.0, 0.25)
        branches = rng.randint(8, 11)
    else:
        h, r = rng.uniform(2.3, 3.2), rng.uniform(0.48, MAX_CANOPY_RADIUS)
        branches = rng.randint(13, 19)
        if kind == "weak":
            leaf_density, fruit_load = rng.uniform(0.4, 0.6), rng.uniform(0.2, 0.5)
        else:
            leaf_density, fruit_load = rng.uniform(0.85, 1.2), rng.uniform(0.6, 1.3)
    volume = (r / 0.55) ** 2 * (h / 2.7)
    return {
        "height": h,
        "trunkHeight": min(rng.uniform(0.55, 0.7), 0.5 * h),
        "trunkRadius": 0.015 + 0.008 * h,
        "canopyRadius": r,
        "branchCount": branches,
        "leafCount": int(round(1300 * leaf_density * volume)),
        "fruitCount": int(round(40 * fruit_load * volume)),
        "ripeFraction": rng.uniform(0.55, 0.95),
        "droop": 0.35 + 0.4 * fruit_load,
    }


def main():
    here = pathlib.Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("world", nargs="?", default=str(here.parent / "worlds/husky_apple.wbt"))
    ap.add_argument("--rows", type=int, default=5)
    ap.add_argument("--per-row", type=int, default=12)
    ap.add_argument("--row-spacing", type=float, default=2.5)
    ap.add_argument("--tree-spacing", type=float, default=1.25)
    ap.add_argument("--jitter", type=float, default=0.05, help="planting error, m (uniform)")
    ap.add_argument("--young", type=float, default=0.12, help="share of young replants")
    ap.add_argument("--weak", type=float, default=0.08, help="share of weak, sparse trees")
    ap.add_argument("--seed", type=int, default=21)
    ap.add_argument("--z", type=float, default=0.14,
                    help="trunk base height, m (on a FieldTerrain bed: bedHeight minus a few cm so it sits IN the soil)")
    a = ap.parse_args()

    clear = a.row_spacing - 2 * MAX_CANOPY_RADIUS
    if clear < ROBOT_WIDTH + 0.2:
        raise SystemExit(f"corridor {clear:.2f} m is too narrow for a {ROBOT_WIDTH} m robot")

    rng = random.Random(a.seed)
    xs = [(i - (a.rows - 1) / 2) * a.row_spacing for i in range(a.rows)]
    ys = [(j - (a.per_row - 1) / 2) * a.tree_spacing for j in range(a.per_row)]
    lines = [BEGIN]
    counts = {"mature": 0, "young": 0, "weak": 0}
    for i, x in enumerate(xs):
        for j, y in enumerate(ys):
            u = rng.random()
            kind = "young" if u < a.young else "weak" if u < a.young + a.weak else "mature"
            counts[kind] += 1
            p = tree_params(rng, kind)
            px = x + rng.uniform(-a.jitter, a.jitter)
            py = y + rng.uniform(-a.jitter, a.jitter)
            yaw = rng.uniform(-3.14159, 3.14159)
            lines.append(
                f'DEF APPLE_R{i + 1}_{j + 1:02d} AppleTree {{\n'
                f'  translation {px:.3f} {py:.3f} {a.z:.3f}\n'
                f'  rotation 0 0 1 {yaw:.3f}\n'
                f'  name "apple r{i + 1} t{j + 1} ({kind})"\n'
                f'  seed {i * 100 + j + 1}\n'
                f'  height {p["height"]:.2f}\n'
                f'  trunkHeight {p["trunkHeight"]:.2f}\n'
                f'  trunkRadius {p["trunkRadius"]:.3f}\n'
                f'  canopyRadius {p["canopyRadius"]:.2f}\n'
                f'  branchCount {p["branchCount"]}\n'
                f'  leafCount {p["leafCount"]}\n'
                f'  fruitCount {p["fruitCount"]}\n'
                f'  ripeFraction {p["ripeFraction"]:.2f}\n'
                f'  droop {p["droop"]:.2f}\n'
                f'}}')
    lines.append(END)
    block = "\n".join(lines)

    world = pathlib.Path(a.world)
    text = world.read_text()
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n" + block + "\n"
    if 'EXTERNPROTO "../protos/AppleTree.proto"' not in text:
        text = text.replace('EXTERNPROTO "../protos/HuskyA300.proto"',
                            'EXTERNPROTO "../protos/HuskyA300.proto"\nEXTERNPROTO "../protos/AppleTree.proto"')
    world.write_text(text)

    corridors = [(xs[k] + xs[k + 1]) / 2 for k in range(len(xs) - 1)]
    print(f"{a.rows} rows x {a.per_row} apple trees -> {world}")
    print(f"  {counts['mature']} mature, {counts['young']} young, {counts['weak']} weak")
    print(f"  rows at x = {', '.join(f'{x:.2f}' for x in xs)}; trees y = {ys[0]:.2f} .. {ys[-1]:.2f}")
    print(f"  corridor centre lines x = {', '.join(f'{c:.2f}' for c in corridors)} "
          f"(clear width >= {clear:.2f} m for a {ROBOT_WIDTH} m robot)")
    print(f"  planted area: x {xs[0] - MAX_CANOPY_RADIUS:.2f}..{xs[-1] + MAX_CANOPY_RADIUS:.2f}, "
          f"y {ys[0] - MAX_CANOPY_RADIUS:.2f}..{ys[-1] + MAX_CANOPY_RADIUS:.2f}")


if __name__ == "__main__":
    main()
